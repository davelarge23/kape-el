create table if not exists public.orders (
  id bigint generated by default as identity primary key,
  session_id text,
  order_archive text not null,
  customer_name text,
  order_number integer not null,
  order_type text not null default 'individual',
  order_source text not null default 'mobile',
  status text not null default 'New',
  reference_number text not null unique,
  total numeric(10,2) default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint orders_status_check
    check (status in ('New', 'Processing', 'Completed', 'Cancelled'))
);

alter table public.orders
  add column if not exists order_source text not null default 'mobile';

alter table public.orders enable row level security;

create policy "Customers can create orders"
  on public.orders for insert
  to anon, authenticated
  with check (true);

create policy "Customers can read orders"
  on public.orders for select
  to anon, authenticated
  using (true);

create policy "Authenticated managers can update orders"
  on public.orders for update
  to authenticated
  using (true)
  with check (true);

alter publication supabase_realtime add table public.orders;